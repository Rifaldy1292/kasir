// SearchProducts performs semantic natural language product search across catalog
func (ctrl *AIController) SearchProducts(c *gin.Context) {
	var dto ProductSearchRequestDto
	if err := c.ShouldBindJSON(&dto); err != nil {
		response.Error(c, http.StatusBadRequest, "Kueri pencarian tidak boleh kosong", err.Error())
		return
	}

	workspaceID := middleware.GetWorkspaceID(c)

	products, err := ctrl.service.SearchProducts(workspaceID, dto.Query)
	if err != nil {
		response.Error(c, http.StatusInternalServerError, "Gagal melakukan pencarian produk AI", err.Error())
		return
	}

	response.Success(c, http.StatusOK, "Pencarian produk AI berhasil", products)
}
