package ai

import (
	"encoding/json"
	"fmt"
	"net/http"

	"gin-quickstart/middleware"
	"gin-quickstart/pkg/response"

	"github.com/gin-gonic/gin"
)

type AIController struct {
	service AIService
}

func NewAIController(service AIService) *AIController {
	return &AIController{service: service}
}

// Chat handles interactive SSE streaming chat with the business AI assistant
func (ctrl *AIController) Chat(c *gin.Context) {
	var dto ChatRequestDto
	if err := c.ShouldBindJSON(&dto); err != nil {
		response.Error(c, http.StatusBadRequest, "Pesan tidak boleh kosong", err.Error())
		return
	}

	workspaceID := middleware.GetWorkspaceID(c)

	// Set headers for Server-Sent Events (SSE) streaming
	c.Writer.Header().Set("Content-Type", "text/event-stream")
	c.Writer.Header().Set("Cache-Control", "no-cache")
	c.Writer.Header().Set("Connection", "keep-alive")
	c.Writer.Header().Set("Transfer-Encoding", "chunked")
	c.Writer.Header().Set("X-Accel-Buffering", "no")

	flusher, ok := c.Writer.(http.Flusher)
	if !ok {
		response.Error(c, http.StatusInternalServerError, "Streaming tidak didukung oleh client", nil)
		return
	}

	err := ctrl.service.StreamChat(workspaceID, dto.SessionID, dto.Message, func(chunk string) error {
		chunkJSON, _ := json.Marshal(map[string]string{"text": chunk})
		_, writeErr := fmt.Fprintf(c.Writer, "data: %s\n\n", string(chunkJSON))
		if writeErr != nil {
			return writeErr
		}
		flusher.Flush()
		return nil
	})

	if err != nil {
		errJSON, _ := json.Marshal(map[string]string{"error": err.Error()})
		fmt.Fprintf(c.Writer, "data: %s\n\n", string(errJSON))
		flusher.Flush()
	}

	// Send terminal signal
	fmt.Fprintf(c.Writer, "data: [DONE]\n\n")
	flusher.Flush()
}

// GetInsights returns automated strategic business insights generated by Gemini
func (ctrl *AIController) GetInsights(c *gin.Context) {
	workspaceID := middleware.GetWorkspaceID(c)

	insights, err := ctrl.service.GetInsights(workspaceID)
	if err != nil {
		response.Error(c, http.StatusInternalServerError, "Gagal menghasilkan wawasan bisnis AI", err.Error())
		return
	}

	response.Success(c, http.StatusOK, "Berhasil memuat wawasan bisnis AI", insights)
}

